class _TextSpace:
    """单站组合空间：模板有序表 + 混合进制分解 + 双射 seq→k 扰乱。"""

    def __init__(self, site: str, templates: list, slots: dict):
        self.site = site
        self.slots = slots
        self.entries = []  # (tpl, slot names, 组合数)
        total = 0
        for tpl in templates:
            names = _SLOT_RE.findall(tpl)
            n = 1
            for nm in names:
                n *= len(slots[nm])
            assert n >= 2, "模板无槽位/组合数过小: %s" % tpl
            self.entries.append((tpl, names, n))
            total += n
        self.size = total
        # 前缀起点（k 定位模板用）
        self._starts = []
        acc = 0
        for _, _, n in self.entries:
            self._starts.append(acc)
            acc += n
        # 双射乘子：与 N 互素的大奇数（黄金比例相位，相邻 seq 落在遥远槽位）
        a = int(self.size * 0.6180339887498949) | 1
        while gcd(a, self.size) != 1:
            a -= 2
        self._mult = a

    def text(self, seq: int, salt: str, topic: str | None = None) -> str:
        b = _h("%s-cmt-b::%s" % (self.site, salt)) % self.size
        k = (self._mult * int(seq) + b) % self.size
        tpl, names, _ = None, None, None
        lo, hi = 0, len(self.entries) - 1
        # 二分定位模板区间
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if self._starts[mid] <= k:
                lo = mid
            else:
                hi = mid - 1
        tpl, names, _ = self.entries[lo]
        k -= self._starts[lo]
        parts = {}
        for nm in reversed(names):
            pool = self.slots[nm]
            parts[nm] = pool[k % len(pool)]
            k //= len(pool)
        # 话题替换：约 1/3 的 t 槽位代入内容真实话题（评论「言之有物」）
        if topic and "t" in parts and _h("%s-cmt-t::%s::%d" % (self.site, salt, seq)) % 3 == 0:
            parts["t"] = topic
        return tpl.format(**parts)


_SPACES_BUILT: dict = {}


def _space(site: str) -> _TextSpace:
    s = _SPACES_BUILT.get(site)
    if s is None:
        templates, slots = _SPACES[site]
        s = _TextSpace(site, templates, slots)
        _SPACES_BUILT[site] = s
    return s


def space_size(site: str) -> int:
    """单站组合空间大小（模板 × 槽位）。"""
    return _space(site).size


def comment_text(site: str, seq: int, salt: str, topic: str | None = None) -> str:
    """第 seq 条评论文本（site 内 salt 命名空间下前 N 条两两不同）。"""
    return _space(site).text(seq, salt, topic=topic)


def _selfcheck() -> dict:
    """模块自检：组合空间规模 + 各站前 5000 seq 双射无重复 + 模板可渲染。"""
    out = {}
    for site in _SPACES:
        sp = _space(site)
        seen = set()
        for i in range(5000):
            t = sp.text(i, "selfcheck")
            assert t and "{" not in t, "模板渲染残留槽位: %s" % t
            seen.add(t)
        out[site] = {"space": sp.size, "distinct_in_5000": len(seen)}
    return out


