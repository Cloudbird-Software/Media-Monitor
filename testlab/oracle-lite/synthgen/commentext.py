def _h(s: str) -> int:
    return int.from_bytes(hashlib.blake2b(s.encode("utf-8"), digest_size=8).digest(), "big")


def _dedup(seq: list) -> list:
    """池内去重（保序）：重复值会让不同数字位渲染出同一文本，破坏双射。"""
    seen = set()
    out = []
    for v in seq:
        if v not in seen:
            seen.add(v)
            out.append(v)
    return out


class _ShortSpace:
    """短评独立组合空间：基词（分站独立池）× 尾符，双射 j→文本。

    R6A-P2-3②：1-5 字短评（这是哪/666/沙发）占 ~14%（stride 路由）；
    R6A-P3-4：分支内双射 ⇒ 同内容深列表短评也两两不同；
    R7A-P3-2：去掉「×语气」维（15/16 语气词结尾是超配主源）——语气词结尾
    改由基词自身按语料频率携带。
    """

    def __init__(self, site: str, bases: list):
        self.site = site
        self.flat = _dedup(bases)
        self.n = len(self.flat) * len(_SHORT_TAILS)
        a = int(self.n * 0.6180339887498949) | 1
        while gcd(a, self.n) != 1:
            a -= 2
        self._mult = a

    def text(self, j: int, salt: str) -> str:
        b = _h("%s-cmt-sb::%s" % (self.site, salt)) % self.n
        k = (self._mult * int(j) + b) % self.n
        tail = _SHORT_TAILS[k % len(_SHORT_TAILS)]
        k //= len(_SHORT_TAILS)
        return self.flat[k % len(self.flat)] + tail


class _TextSpace:
    """单站组合空间：模板有序表 + 混合进制分解 + 双射 seq→k 扰乱。

    R6A-P2-3/P3-4：短评分支（stride 路由 + 独立双射）与表情后缀均按
    (salt, seq) 哈希确定性决定；「话题替换 + 补偿重掷」把被替换的 t 槽位
    信息编码进另一槽位，替换后依然近似单射（深列表零重复的关键）。
    """

    def __init__(self, site: str, templates: list, slots: dict):
        self.site = site
        self.slots = {k: _dedup(v) for k, v in slots.items()}
        slots = self.slots
        self.entries = []  # (tpl, slot names, 组合数)
        total = 0
        for tpl in templates:
            # R6A-P3-4 均衡扩容：不以标点收尾的模板统一追加 {endp} 尾槽
            # （全部模板空间等比放大 ×|endp|，长度/风格混配不变）
            if "endp" in slots and not tpl.rstrip().endswith(_END_TRAIL):
                tpl = tpl + "{endp}"
            names = _SLOT_RE.findall(tpl)
            n = 1
            for nm in names:
                n *= len(slots[nm])
            assert n >= 2, "模板无槽位/组合数过小: %s" % tpl
            self.entries.append((tpl, names, n))
            total += n
        self.size = total
        self._starts = []
        acc = 0
        for _, _, n in self.entries:
            self._starts.append(acc)
            acc += n
        # 双射乘数：与 N 互素的大奇数（黄金比例相位，相邻 seq 落在遥远槽位）
        a = int(self.size * 0.6180339887498949) | 1
        while gcd(a, self.size) != 1:
            a -= 2
        self._mult = a
        self.emoji_pool = _EMOJI_POOLS[site]
        self.shorts = _ShortSpace(site, _SHORT_BASES[site])

    # ---- 表情后缀（R6A-P2-3①）----
    def _emoji_suffix(self, seq: int, salt: str) -> str:
        h = _h("%s-cmt-emoji::%s::%d" % (self.site, salt, seq))
        r = (h % 10000) / 10000.0
        if r >= _EMOJI_RATE[self.site]:
            return ""
        pool = self.emoji_pool
        first = pool[(h >> 16) % len(pool)]
        if ((h >> 40) % 10000) / 10000.0 < _EMOJI_DBL:
            return first + pool[(h >> 28) % len(pool)]
        return first

    def text(self, seq: int, salt: str, topic: str | None = None) -> str:
        # 短评分支（R6A-P2-3②）：stride 路由（~14%），分支内双射（R6A-P3-4）
        r0 = _h("%s-cmt-r0::%s" % (self.site, salt)) % _SHORT_STRIDE
        if int(seq) % _SHORT_STRIDE == r0:
            return self.shorts.text(int(seq) // _SHORT_STRIDE, salt) \
                + self._emoji_suffix(seq, salt)
        b = _h("%s-cmt-b::%s" % (self.site, salt)) % self.size
        k = (self._mult * int(seq) + b) % self.size
        lo, hi = 0, len(self.entries) - 1
        # 二分定位模板区间
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if self._starts[mid] <= k:
                lo = mid
            else:
                hi = mid - 1
        tpl, names, _ = self.entries[lo]
        k -= self._starts[lo]
        parts = {}
        for nm in reversed(names):
            pool = self.slots[nm]
            parts[nm] = pool[k % len(pool)]
            k //= len(pool)
        # 话题替换（R6A-P3-4 单射版）：仅当 t 槽位自然取值 == 池首词且
        # topic 不在池内时替换为真实话题——替换条件是 k 分解的确定性函数
        # （t 数字位 == 0），不同 k 替换后仍可区分，双射不破坏。
        if topic and "t" in parts and parts["t"] == self.slots["t"][0] \
                and topic not in self.slots["t"]:
            parts["t"] = topic
        return tpl.format(**parts) + self._emoji_suffix(seq, salt)


_SPACES_BUILT: dict = {}


def _space(site: str) -> _TextSpace:
    s = _SPACES_BUILT.get(site)
    if s is None:
        templates, slots = _SPACES[site]
        s = _TextSpace(site, templates, slots)
        _SPACES_BUILT[site] = s
    return s


def space_size(site: str) -> int:
    """单站组合空间大小（模板 × 槽位）。"""
    return _space(site).size


def comment_text(site: str, seq: int, salt: str, topic: str | None = None) -> str:
    """第 seq 条评论文本（site 内 salt 命名空间下前 N 条两两不同）。"""
    return _space(site).text(seq, salt, topic=topic)


def has_emoji_marker(text: str, site: str) -> bool:
    """站内括号表情判定（validate/复核共用）：xhs 为 [xxR]，dy/ks 为 [xx]。"""
    if site == "xhs":
        return re.search(r"\[[^\[\]]{1,6}R\]", text) is not None
    return re.search(r"\[[^\[\]R]{1,6}\]", text) is not None


def _selfcheck() -> dict:
    """模块自检：组合空间规模 + 各站前 20000 seq 双射无重复 + 模板可渲染。

    R6A-P3-4 断言：单内容 6000 条评论零重复（dy 深列表 >71 条重复的根治验证，
    含话题替换路径；R7A-P3-2 后短评分支容量=基词×尾符，最深探针 600 条）；
    跨内容（不同 salt）前 400 条重叠 < 2%（ks 同题材重叠 24-75% 的根治验证）；
    长度分位对齐语料（p10≤6 / p50 8-16 / p90≥22）。
    """
    out = {}
    for site in _SPACES:
        sp = _space(site)
        seen = set()
        lengths = []
        emoji_n = 0
        # R7A-P3-2：20000 → 6000（短评分支改为基词×尾符后容量 = 基词×13×7；
        # 6000 seq 的单内容深列表（含 ~857 条短评）仍严格双射，红队最深探针 600 条）
        for i in range(6000):
            t = sp.text(i, "selfcheck", topic="咖啡拉花")
            assert t and "{" not in t, "模板渲染残留槽位: %s" % t
            seen.add(t)
            lengths.append(len(t))
            if has_emoji_marker(t, site):
                emoji_n += 1
        lengths.sort()
        s1 = {sp.text(i, "saltA") for i in range(400)}
        s2 = {sp.text(i, "saltB") for i in range(400)}
        out[site] = {
            "space": sp.size,
            "distinct_in_6000": len(seen),
            "len_p10": lengths[600], "len_p50": lengths[3000], "len_p90": lengths[5400],
            "emoji_rate": round(emoji_n / 6000, 3),
            "cross_overlap_400": len(s1 & s2),
        }
    return out


